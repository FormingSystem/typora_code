import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'terminal_log_'));
await build({entryPoints:['src/terminal_log.ts'],bundle:true,platform:'node',format:'esm',outfile:path.join(root,'log.mjs')});
const {terminal_log}=await import(pathToFileURL(path.join(root,'log.mjs')));
const errors=[];
const log=new terminal_log(fs,path,path.join(root,'spool'),error=>errors.push(String(error)));
const output=path.join(root,'中文 output.log'),snapshot=path.join(root,'snapshot.log');
await log.append('start\r\n\x1b[');await log.append('31m中文\x1b[0m\x1b]0;title');await log.append('\x07\n');
await log.append('\ud83d');await log.append('\ude00\n');
await log.save(output,true);
assert.equal(fs.readFileSync(output,'utf8'),'start\r\n中文\n😀\n');
const block='line 中文 '+ 'x'.repeat(1024)+'\nrow\n'.repeat(200);
for(let i=0;i<1000;i++)await log.append(block);
const before=fs.statSync(output).size;
const saving=log.save(snapshot);const more=log.append('later\n');await saving;await more;
assert.equal(fs.statSync(snapshot).size,before);
assert.equal(fs.statSync(output).size,before+6);
await log.stop();await log.append('after stop\n');assert.equal(fs.statSync(output).size,before+6);
await log.save(snapshot);assert(fs.readFileSync(snapshot,'utf8').endsWith('later\nafter stop\n'));
await log.save(output,true);
const other=new terminal_log(fs,path,path.join(root,'spool'),error=>errors.push(String(error)));
await other.append('separate');await assert.rejects(other.save(output,true),/already in use/);
await other.dispose();await log.stop();await log.dispose();
assert.equal(fs.readdirSync(path.join(root,'spool')).length,0);assert(fs.existsSync(output));
const broken=new terminal_log({...fs,promises:{...fs.promises,appendFile:async()=>{throw Error('ENOSPC');}}},path,path.join(root,'spool'),error=>errors.push(String(error)));
await broken.append('missing');await assert.rejects(broken.save(snapshot),/ENOSPC/);await broken.dispose();assert.equal(errors.length,1);
console.log('terminal log: UTF-8, split controls, 1000 blocks, ordered snapshot, continuous stop, isolation, disk failure, cleanup PASS');
